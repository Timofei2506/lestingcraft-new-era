"""Compile one authored architecture source to identical Burst-compatible C# / JS tables.
Run from any directory: python3 Tools/build_architecture.py [--check].
Frozen content <=10 plans are imported, never reauthored here.
"""
import json,subprocess,sys,hashlib
from pathlib import Path
sys.path.insert(0,str(Path(__file__).parent/'WorldGen'))
from architecture import PLANS
ROOT=Path(__file__).resolve().parents[1]

def compile_plans():
 columns=[];bases=[0];offsets=[0];runs=[];intern={};report=[]
 for p in PLANS:
  r=p.radius;w=2*r+1
  # Apply ordered inclusive boxes to a compact [-8,48] voxel volume.
  layers=[bytearray([1 if y<0 else 3 if y==0 else 0])*(w*w) for y in range(-8,49)]
  for x0,x1,y0,y1,z0,z1,id in p.boxes:
   fill=bytes([id])*(x1-x0+1)
   for y in range(y0,y1+1):
    for z in range(z0,z1+1):
     a=x0+r+w*(z+r);layers[y+8][a:a+len(fill)]=fill
  for z in range(-r,r+1):
   for x in range(-r,r+1):
    at=x+r+w*(z+r);seq=[];start=None;last=None
    for y in range(-8,50):
     id=layers[y+8][at] if y<49 else None
     default=1 if y<0 else 3 if y==0 else 0
     override=id if id!=default else None
     if override!=last:
      if last is not None:seq.extend([start,y-1,last])
      start=y;last=override
    key=tuple(seq)
    if key not in intern:
     intern[key]=len(offsets)-1;runs.extend(seq);offsets.append(len(runs))
    columns.append(intern[key])
  bases.append(len(columns))
  report.append({'name':p.name,'radius':r,'boxes':len(p.boxes),'entrances':p.entrances,'top':max(b[3] for b in p.boxes)})
 return columns,bases,offsets,runs,report

def cs_array(name,values):
 lines=[','.join(map(str,values[i:i+96])) for i in range(0,len(values),96)]
 return '        public static readonly int[] '+name+' = {\n            '+',\n            '.join(lines)+'\n        };\n'

def outputs():
 c,b,o,r,report=compile_plans();data={'radii':[p.radius for p in PLANS],'bases':b,'columns':c,'offsets':o,'runs':r}
 src='// Generated by Tools/build_architecture.py. Do not edit. Content <=10 is untouched.\nnamespace LestingCraft.World\n{\n    public static class ArchitecturePlan\n    {\n        public const int Version=11;\n'
 for name,values in [('Radius',data['radii']),('Bases',b),('Columns',c),('Offsets',o),('Runs',r)]:src+=cs_array(name,values)
 src+='''        public static ushort Apply(int kind,int x,int y,int z)
        {
            int radius=Radius[kind],width=radius*2+1;
            int pattern=Columns[Bases[kind]+x+radius+width*(z+radius)];
            for(int i=Offsets[pattern];i<Offsets[pattern+1];i+=3)
                if(y>=Runs[i]&&y<=Runs[i+1])return (ushort)Runs[i+2];
            return (ushort)(y<0?1:y==0?3:0);
        }
    }
}
'''
 js='// Generated by Tools/build_architecture.py; ordered-box geometry compiled into deduplicated vertical runs.\nconst data='+json.dumps(data,separators=(',',':'))+';\nexport const architectureVersion=11;\nexport const architectureSummary='+json.dumps(report,ensure_ascii=False,separators=(',',':'))+''';
export function architectureBlock(kind,x,y,z){
 const radius=data.radii[kind],width=radius*2+1;
 const pattern=data.columns[data.bases[kind]+x+radius+width*(z+radius)];
 for(let i=data.offsets[pattern];i<data.offsets[pattern+1];i+=3)
  if(y>=data.runs[i]&&y<=data.runs[i+1])return data.runs[i+2];
 return y<0?1:y===0?3:0;
}
'''
 legacy=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import {plans} from './Server/src/structure-plan.js';console.log(JSON.stringify(plans));"],cwd=ROOT,text=True))
 boxes=[];offs=[0]
 for p in legacy:boxes+=p['boxes'];offs.append(len(boxes))
 frozen='// Generated from the frozen Server/src/structure-plan.js by Tools/build_architecture.py.\nnamespace LestingCraft.World { public static class StructurePlan {\n'
 frozen+=cs_array('Radius',[p['radius'] for p in legacy])+cs_array('Offsets',offs)+cs_array('Boxes',boxes)+'} }\n'
 manifest={'contentVersion':11,'authoringSHA256':hashlib.sha256((ROOT/'Tools/WorldGen/architecture.py').read_bytes()).hexdigest(),'plans':report,'uniqueColumnPatterns':len(o)-1,'columns':len(c),'verticalRuns':len(r)//3}
 return {ROOT/'Assets/Scripts/World/ArchitecturePlan.cs':src,ROOT/'Assets/Scripts/World/StructurePlan.cs':frozen,ROOT/'Server/src/architecture-plan.js':js,ROOT/'Assets/Resources/Models/Architecture-v11.json':json.dumps(manifest,ensure_ascii=False,indent=2)+'\n'}

if __name__=='__main__':
 failed=False
 for p,text in outputs().items():
  if '--check' in sys.argv:
   if not p.exists() or p.read_text()!=text:print('STALE',p.relative_to(ROOT));failed=True
  else:p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text);print('WRITE',p.relative_to(ROOT),len(text),'characters')
 if failed:raise SystemExit(1)
 print('PASS reproducible architecture tables' if '--check' in sys.argv else 'Architecture compiled')
